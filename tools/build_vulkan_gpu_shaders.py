"""Compile the original engine's shared raster rules for the native Vulkan backend.

Run with the NDK glslc executable; generated SPIR-V is committed so normal Android
builds do not require Python. No third-party renderer shader sources are used.
"""
import argparse
from pathlib import Path
import re
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CPP = ROOT / 'psxlab/app/src/main/cpp'
PARAMS = '''layout(push_constant) uniform Parameters {
    ivec4 bounds; ivec4 data; ivec4 shape; ivec4 display;
    int count; int countPixels; int serialMode; int snapshot;
    int operation; int status; int replacementTextures; int smoothImage;
};
layout(constant_id=0) const int scale=1;
'''


def extract(filename, name):
    text = (CPP / filename).read_text(encoding='utf-8')
    return re.search(r'\b' + name + r'=R"GLSL\((.*?)\)GLSL";', text, re.S)[1]


def convert(source, name):
    source = source.replace('#version 310 es', '#version 450')
    source = re.sub(r'^#extension GL_EXT_shader_framebuffer_fetch.*\n', '', source, flags=re.M)
    source = re.sub(r'uniform (?:int|ivec4) \w+;', '', source)
    source = source.replace('gl_InstanceID', 'gl_InstanceIndex').replace('gl_VertexID', 'gl_VertexIndex')
    source = source.replace('layout(r32ui,binding=1)', 'layout(r32ui,binding=4)')
    source = source.replace('layout(rgba8,binding=0)', 'layout(rgba8,binding=6)')
    source = source.replace('uniform highp usampler2D hdRead;', 'layout(binding=7) uniform highp usampler2D hdRead;')
    if name == 'HdDraw':
        begin, end = source.index('int texturePixel('), source.index('void drawAt(')
        source = source[:begin] + source[begin:end].replace('imageLoad(hdImage,', 'imageLoad(hdReadImage,') + source[end:]
        source = source.replace('void drawAt(', 'layout(r32ui,binding=5) readonly uniform highp uimage2D hdReadImage;\nvoid drawAt(', 1)
        # The declaration must precede texturePixel, which references it.
        declaration = 'layout(r32ui,binding=5) readonly uniform highp uimage2D hdReadImage;\n'
        source = source.replace(declaration, '')
        source = source.replace('int texturePixel(', declaration + 'int texturePixel(', 1)
    if name == 'OpaqueFragment':
        source = source.replace('layout(location=0) inout highp uvec4 destination;', 'layout(location=0) out highp uvec4 destination;')
        source = source.replace('int back=int(destination.r);if((pEnv.y&2)!=0&&(back&32768)!=0)discard;', 'int back=0;')
    if name == 'OrderedFragment':
        source = source.replace('layout(location=0) inout highp uvec4 destination;', 'layout(input_attachment_index=0,binding=8) uniform usubpassInput backImage;\nlayout(location=0) out highp uvec4 destination;')
        source = source.replace('int back=int(destination.r);', 'int back=int(subpassLoad(backImage).r);')
    if name == 'NativeResolve':
        source = source.replace('uniform uvec2 dirtyRows[32];', 'layout(std430,binding=1) readonly buffer Tiles {uvec2 dirtyRows[];};')
    return source.replace('#version 450', '#version 450\n' + PARAMS, 1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--compiler', required=True)
    parser.add_argument('--output', type=Path, default=CPP / 'vulkan_gpu_shaders.h')
    args = parser.parse_args()
    shaders = [
        ('Draw', 'gpu_shaders.h', 'DRAW_SHADER', 'comp'),
        ('Transfer', 'gpu_shaders.h', 'TRANSFER_SHADER', 'comp'),
        ('Scanout', 'gpu_shaders.h', 'SCANOUT_SHADER', 'comp'),
        ('HdDraw', 'hd_gpu_shaders.h', 'HD_DRAW_SHADER', 'comp'),
        ('HdTransfer', 'hd_gpu_shaders.h', 'HD_TRANSFER_SHADER', 'comp'),
        ('HdScanout', 'hd_gpu_shaders.h', 'HD_SCANOUT_SHADER', 'comp'),
        ('OpaqueVertex', 'hd_gpu_shaders.h', 'HD_RASTER_VERTEX', 'vert'),
        ('OpaqueFragment', 'hd_gpu_shaders.h', 'HD_RASTER_FRAGMENT', 'frag'),
        ('OrderedFragment', 'hd_gpu_shaders.h', 'HD_RASTER_FRAGMENT', 'frag'),
        ('NativeResolve', 'hd_gpu_shaders.h', 'HD_NATIVE_RESOLVE_SHADER', 'comp'),
    ]
    generated = ['// Generated by tools/build_vulkan_gpu_shaders.py from the original engine shaders.',
                 '#pragma once', '#include <cstdint>', 'namespace PsxVulkanShaders {']
    with tempfile.TemporaryDirectory(prefix='armsx-vulkan-shaders-') as temp:
        for name, filename, constant, stage in shaders:
            path = Path(temp) / (name + '.' + stage)
            path.write_text(convert(extract(filename, constant), name), encoding='utf-8')
            binary = path.with_suffix('.spv')
            subprocess.run([args.compiler, str(path), '--target-env=vulkan1.0', '-fauto-map-locations', '-O', '-o', str(binary)], check=True)
            code = binary.read_bytes()
            validator = Path(args.compiler).with_name('spirv-val.exe' if Path(args.compiler).suffix == '.exe' else 'spirv-val')
            if validator.exists():
                subprocess.run([str(validator), '--target-env', 'vulkan1.0', str(binary)], check=True)
            words = struct.unpack('<' + 'I' * (len(code) // 4), code)
            generated.append('inline constexpr uint32_t ' + name + '[]={')
            generated.extend('    ' + ','.join(f'0x{word:08x}' for word in words[i:i+8]) + ',' for i in range(0, len(words), 8))
            generated.append('};')
            print(f'{name}: {len(code)} bytes, validated')
    generated.append('}')
    args.output.write_text('\n'.join(generated) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
