#!/usr/bin/env python3
"""Regenerate psxlab/app/src/main/cpp/frame_generation_spirv.h from the GLSL in frame_generation.h.

    python psxlab/tools/framegen/build_shaders.py [path/to/glslc]

The GLSL strings in frame_generation.h are the only source: the Vulkan display runs this SPIR-V,
the OpenGL display compiles the same text as GLES 3.1 at run time. Both variants are compiled
here, so a shader that would only fail on a GLES driver fails on the desktop first.
"""
import glob
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HEADER = os.path.join(ROOT, "app", "src", "main", "cpp", "frame_generation.h")
OUTPUT = os.path.join(ROOT, "app", "src", "main", "cpp", "frame_generation_spirv.h")
PASSES = [("kLumaShader", "Luma"), ("kCoarseShader", "Coarse"), ("kCoarseMotionShader", "CoarseMotion"),
          ("kFineMotionShader", "FineMotion"), ("kInterpolateShader", "Interpolate")]


def find_glslc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    sdk = os.environ.get("ANDROID_HOME") or os.path.expanduser("~/AppData/Local/Android/Sdk")
    found = sorted(glob.glob(os.path.join(sdk, "ndk", "*", "shader-tools", "*", "glslc*")))
    if not found:
        sys.exit("glslc not found; pass its path")
    return found[-1]


def strings(text):
    return {m.group(1): m.group(2) for m in re.finditer(r'constexpr const char\* (\w+) = R"GLSL\((.*?)\)GLSL";', text, re.S)}


def compile_stage(glslc, source, target, name, workdir):
    path = os.path.join(workdir, name + ".comp")
    with open(path, "w", newline="\n") as f:
        f.write(source)
    out = os.path.join(workdir, name + (".inc" if target == "vulkan" else ".spv"))
    if target == "vulkan":
        command = [glslc, "-O", "--target-env=vulkan1.0", "-mfmt=c", path, "-o", out]
    else:
        # GLES 3.1 cannot target SPIR-V; compile the ES text as an OpenGL module purely to check it.
        command = [glslc, "--target-env=opengl", "-fauto-map-locations", path, "-o", out]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"{name} ({target}) failed:\n{result.stdout}{result.stderr}")
    return out


def main():
    glslc = find_glslc()
    with open(HEADER, encoding="utf-8") as f:
        text = f.read()
    s = strings(text)
    lines = ["#pragma once", "#include <cstdint>", "#include <cstddef>",
             "// Generated by psxlab/tools/framegen/build_shaders.py from the GLSL in frame_generation.h. Do not edit.",
             "namespace psxfg {"]
    with tempfile.TemporaryDirectory() as workdir:
        for key, name in PASSES:
            gles = s["kGlesPrelude"] + s["kCommon"] + s[key]
            compile_stage(glslc, gles, "opengl", name + "Gles", workdir)
            vulkan = s["kVulkanPrelude"] + s["kCommon"] + s[key]
            inc = compile_stage(glslc, vulkan, "vulkan", name, workdir)
            with open(inc) as f:
                words = f.read().strip()
            lines.append(f"static const uint32_t k{name}Spirv[] = {words};")
    lines.append("inline const uint32_t* passSpirv(int pass, size_t* bytes) {")
    lines.append("    switch (pass) {")
    for index, (_, name) in enumerate(PASSES):
        lines.append(f"        case {index}: *bytes = sizeof(k{name}Spirv); return k{name}Spirv;")
    lines.append("        default: *bytes = 0; return nullptr;")
    lines.append("    }")
    lines.append("}")
    lines.append("}  // namespace psxfg")
    with open(OUTPUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUTPUT)


if __name__ == "__main__":
    main()
